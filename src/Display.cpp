void display_app(void *pvParameter)
{
    printf("Starting Display application\n");
    display_init();
    while(1)
    {
        vTaskDelay(1000 / portTICK_PERIOD_MS);
    }
}

esp_err_t display_init()
{
    // Configure SPI bus
    esp_err_t ret = ESP_OK;

    spi_bus_config_t cfg = {
        .mosi_io_num = MOSI_PIN,
        .miso_io_num = MISO_PIN,
        .sclk_io_num = CLK_PIN,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .data4_io_num = -1,
        .data5_io_num = -1,
        .data6_io_num = -1,
        .data7_io_num = -1,
        .data_io_default_level = false,
        .max_transfer_sz = 4096, // Adjust based on your needs
        .flags = SPICOMMON_BUSFLAG_MASTER | SPICOMMON_BUSFLAG_SCLK | SPICOMMON_BUSFLAG_MOSI | SPICOMMON_BUSFLAG_MISO,
        .isr_cpu_id = ESP_INTR_CPU_AFFINITY_AUTO,
        .intr_flags = ESP_INTR_FLAG_LEVEL1
    };
    spi_bus_initialize(HOST, &cfg, SPI_DMA_CH_AUTO);

    // Configure device
    max7219_t dev = {};
    dev.digits = 0; // overwrite 8*CASCADE_SIZE column
    dev.cascade_size = CASCADE_SIZE;
    dev.mirrored = true;

    max7219_init_desc(&dev, HOST, MAX7219_MAX_CLOCK_SPEED_HZ, CS_PIN);
    max7219_init(&dev);
    max7219_set_brightness(&dev, MAX7219_MAX_BRIGHTNESS/2);

    while (1)
    {
        printf("---------- draw\n");
        for (uint8_t i = 0; i < 9; i ++)
        {
            for (uint8_t c = 0; c < CASCADE_SIZE; c ++)
            {
                for(uint8_t index= 0; index < 8; index++)
                {
                    max7219_set_digit(&dev, c*8+index, array_list[i][c][index]);
                }
            }
            vTaskDelay(700 / portTICK_PERIOD_MS);
        }
    }

    return ret;
}

